#!/bin/bash
# Waits for run_soak_b.sh to finish, then writes the soak table into X1b-results.md.
cd /home/mike/code/trellis-lane-r/research/absolute-build/x1b
until grep -qE "FINISHED|reserve failed" run_soak_b.out; do sleep 30; done
grep -q SOAK_PLACEHOLDER X1b-results.md || exit 0
python3 - <<'PY'
import subprocess
t = subprocess.run(["python3", "summarize_b.py", "soak_b.jsonl"], capture_output=True, text=True).stdout
fin = [l for l in open("run_soak_b.out") if l.startswith("FINISHED")]
lid = open("logbook_id.txt").read().strip() if __import__("os").path.exists("logbook_id.txt") else "?"
body = (f"Logbook id **`{lid}`** ({fin[-1].strip() if fin else 'not finished'}). 20 s runs, 8 in parallel, "
        "appliers 2/4/8, X1's workload plus: in-order retirement on; leaf variants build as 4 transactions with "
        "0-40 ms jitter between them; `+T` variants maintain the target and add a `resume` mode (1-3 uncaptured "
        "source changes, `h` emptied, `tgt` kept). Table generated by `summarize_b.py` (auto-filled by "
        "`fill_soak.sh`; interpretation below it, if present, was written after).\n\n" + t)
s = open("X1b-results.md").read().replace("SOAK_PLACEHOLDER", body)
open("X1b-results.md", "w").write(s)
PY
